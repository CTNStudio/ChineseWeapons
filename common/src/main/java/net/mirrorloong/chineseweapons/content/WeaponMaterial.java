package net.mirrorloong.chineseweapons.content;

/**
 * The vanilla tool materials used by the special weapons. 26.1 renamed
 * {@code Tier} to {@code ToolMaterial}, so shared code names the material by
 * this enum and each target maps it to its own type.
 */
public enum WeaponMaterial {
    WOOD,
    STONE,
    GOLD,
    IRON,
    DIAMOND,
    NETHERITE
}
